#!/bin/bash
# Builds "Unique AV RF Scan Co-ord.app" (native macOS app) into ./build
#
#   ./build_app.sh                      build for this Mac
#   UNIVERSAL=1 ./build_app.sh          Apple Silicon + Intel (needs full Xcode)
#   VERSION=1.2.0 ./build_app.sh        stamp a version (used by the release workflow)
#
# Requirements: macOS 13+ and Xcode or the Xcode Command Line Tools (xcode-select --install)
set -euo pipefail
cd "$(dirname "$0")"

ARCH_FLAGS=()
if [ "${UNIVERSAL:-0}" = "1" ]; then ARCH_FLAGS=(--arch arm64 --arch x86_64); fi

# Licensing / distribution settings for release builds (see LICENSING.md). When set, they are
# compiled into the app via Sources/UniqueAV/BuildConfig.swift, which is restored afterwards.
CONFIG=Sources/UniqueAV/BuildConfig.swift
if [ -n "${KEYGEN_ACCOUNT_ID:-}" ]; then
  for v in KEYGEN_ACCOUNT_ID KEYGEN_PUBLIC_KEY TRIAL_URL PURCHASE_URL RELEASES_REPO; do
    if printf '%s' "${!v:-}" | grep -q '["\\]'; then echo "✗ $v contains quotes or backslashes"; exit 1; fi
  done
  [[ "$KEYGEN_PUBLIC_KEY" =~ ^[0-9a-fA-F]{64}$ ]] || { echo "✗ KEYGEN_PUBLIC_KEY must be the 64-character hex Ed25519 verify key"; exit 1; }
  cp "$CONFIG" "$CONFIG.orig"
  trap 'mv -f "$CONFIG.orig" "$CONFIG"' EXIT
  cat > "$CONFIG" <<SWIFT
// Generated by build_app.sh for a release build.
enum BuildConfig {
    static let keygenAccountID = "${KEYGEN_ACCOUNT_ID}"
    static let keygenPublicKey = "${KEYGEN_PUBLIC_KEY}"
    static let trialURL = "${TRIAL_URL:-}"
    static let purchaseURL = "${PURCHASE_URL:-}"
    static let releasesRepo = "${RELEASES_REPO:-Jeansenekal-tech/rf-microphone-control-and-scan-}"
}
SWIFT
  echo "▸ Licensing enabled (Keygen account ${KEYGEN_ACCOUNT_ID})"
else
  echo "▸ Licensing not configured – building an unlicensed developer build"
fi

echo "▸ Building release binary…"
swift build -c release "${ARCH_FLAGS[@]+"${ARCH_FLAGS[@]}"}"
BIN="$(swift build -c release "${ARCH_FLAGS[@]+"${ARCH_FLAGS[@]}"}" --show-bin-path)/UniqueAV"

APP="build/Unique AV RF Scan Co-ord.app"
echo "▸ Assembling ${APP}…"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN" "$APP/Contents/MacOS/UniqueAV"
cp Resources/Info.plist "$APP/Contents/Info.plist"
if [ -d Resources/AppIcon.iconset ]; then
  iconutil -c icns Resources/AppIcon.iconset -o "$APP/Contents/Resources/AppIcon.icns"
fi

if [ -n "${VERSION:-}" ]; then
  /usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $VERSION" "$APP/Contents/Info.plist"
  /usr/libexec/PlistBuddy -c "Set :CFBundleVersion ${BUILD_NUMBER:-$VERSION}" "$APP/Contents/Info.plist"
fi

echo "▸ Signing (ad-hoc)…"
codesign --force --deep --sign - "$APP"

echo "✓ Done: $APP ($(/usr/libexec/PlistBuddy -c 'Print :CFBundleShortVersionString' "$APP/Contents/Info.plist"))"
echo "  Open it with:  open \"$APP\"   (or drag it to /Applications)"
